    signingConfigs {
        create("release") {
            if (keystorePropertiesFile.exists()) {
                val storeFilePath = keystoreProperties.getProperty("storeFile")
                storeFile = if (!storeFilePath.isNullOrBlank()) {
                    val rawFile = File(storeFilePath)
                    if (rawFile.isAbsolute) rawFile
                    else if (file(storeFilePath).exists()) file(storeFilePath)
                    else rootProject.file(storeFilePath)
                } else null
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            } else {
                storeFile = rootProject.file("MISSING_keystore.properties_see_RELEASE.md")
            }
        }
        create("debugConfig") {
            storeFile = file("${rootDir}/debug.keystore")
            storePassword = "android"
            keyAlias = "androiddebugkey"
            keyPassword = "android"
        }
    }

    buildTypes {
        release {
            isCrunchPngs = false
            isMinifyEnabled = true
