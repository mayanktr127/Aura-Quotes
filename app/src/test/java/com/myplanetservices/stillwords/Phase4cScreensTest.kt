@RunWith(RobolectricTestRunner::class)
@Config(sdk = [34])
class Phase4cScreensTest {

    @get:Rule
    val composeTestRule = createComposeRule()

    @Test
    fun testHistoryWithDuplicateQuotes_usesUniqueHistoryItemIds() {
        val sampleQuote = Quote(
            id = "q_stoic_1",
            text = "Waste no more time arguing about what a good man should be. Be one.",
            author = "Marcus Aurelius",
            category = "Discipline"
        )

        // Same quote read twice, with two different history entry IDs (as generated by Room auto-increment)
        val historyEntries = listOf(
            HistoryItem(id = 101L, viewedAt = 1000L, quote = sampleQuote),
            HistoryItem(id = 102L, viewedAt = 2000L, quote = sampleQuote),
            HistoryItem(id = 103L, viewedAt = 3000L, quote = sampleQuote.copy(id = "q_stoic_2", text = "The obstacle is the way."))
        )

        // Verify all keys are strictly distinct
        val keys = historyEntries.map { "hist_${it.id}" }
        assertEquals(3, keys.toSet().size)

        // Render LazyColumn using the exact key logic used in FavoritesScreen
        composeTestRule.setContent {
            StillwordsTheme(darkTheme = true) {
                LazyColumn(modifier = Modifier.fillMaxSize()) {
                    items(
                        items = historyEntries,
                        key = { "hist_${it.id}" },
                        contentType = { "history_row" }
                    ) { item ->
                        Text(text = "Entry ${item.id}: ${item.quote.text}")
                    }
                }
            }
        }

        // Verify elements rendered without Compose key collision crash
        composeTestRule.onNodeWithText("Entry 101: Waste no more time arguing about what a good man should be. Be one.")
            .assertIsDisplayed()
        composeTestRule.onNodeWithText("Entry 102: Waste no more time arguing about what a good man should be. Be one.")
            .assertIsDisplayed()
        composeTestRule.onNodeWithText("Entry 103: The obstacle is the way.")
            .assertIsDisplayed()
    }

    @Test
    fun testMomentsMapping_hasApprovedCategories() {
        val morning = ExploreUiState.MOMENT_MAPPING["Morning"]
        val beforeWork = ExploreUiState.MOMENT_MAPPING["Before work"]
        val studyTime = ExploreUiState.MOMENT_MAPPING["Study time"]
        val beforeSleep = ExploreUiState.MOMENT_MAPPING["Before sleep"]

        assertNotNull(morning)
        assertEquals(listOf("Peace", "Gratitude", "Mindfulness", "Motivation"), morning)

        assertNotNull(beforeWork)
        assertEquals(listOf("Discipline", "Work", "Confidence", "Success"), beforeWork)

        assertNotNull(studyTime)
        assertEquals(listOf("Study", "Wisdom", "Creativity", "Growth"), studyTime)

        assertNotNull(beforeSleep)
        assertEquals(listOf("Peace", "Healing", "Life", "Mindfulness"), beforeSleep)
    }

    @Test
    fun testSearchFilterLabels() {
        assertEquals("All", SearchFilter.ALL.label)
        assertEquals("Quotes", SearchFilter.QUOTES.label)
        assertEquals("Topics", SearchFilter.TOPICS.label)
        assertEquals("Authors", SearchFilter.AUTHORS.label)
    }

    @Test
    fun testUserQuotesFiltering_identifiesCreatedQuotes() {
        val sampleQuotes = listOf(
            Quote(
                id = "q_1",
                text = "Curated stoic quote",
                author = "Seneca",
                category = "Wisdom",
                isUserCreated = false
            ),
            Quote(
                id = "user_101",
                text = "My personal quiet thought",
                author = "You",
                category = "Personal",
                isUserCreated = true
            )
        )

        val userQuotes = sampleQuotes.filter { it.isUserCreated }
        assertEquals(1, userQuotes.size)
        assertEquals("user_101", userQuotes[0].id)
        assertEquals("My personal quiet thought", userQuotes[0].text)
    }
}
